import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const ctx = await b.newContext({ viewport: { width: 375, height: 800 } });
const [n, ...r] = process.env.COOKIE.trim().split('='); await ctx.addCookies([{ name: n, value: r.join('='), domain: '127.0.0.1', path: '/' }]);
const p = await ctx.newPage();
const ok = (name, v) => console.log((v ? 'OK    ' : 'ÉCHEC ') + name);
await p.goto('http://127.0.0.1:8002/works');
await p.getByRole('button', { name: 'Ouvrir le menu' }).click(); await p.waitForTimeout(400);
ok('Menu mobile ouvert (x-show)', await p.locator('#menu-mobile').isVisible());
await p.goto('http://127.0.0.1:8002/works/articles/ce-que-la-sociologie-dit-vraiment-du-teletravail');
await p.mouse.wheel(0, 2000); await p.waitForTimeout(400);
ok('Barre de progression de lecture (x-bind:style objet)', (await p.locator('header [aria-hidden="true"].origin-left').getAttribute('style') || '').includes('scaleX'));
await p.setViewportSize({ width: 1280, height: 800 });
await p.goto('http://127.0.0.1:8002/dashboard/profil?onglet=mot-de-passe');
const pw = p.locator('input[type=password]').nth(1); await pw.fill('Tres-Robuste-Phrase-2026!');
await p.waitForTimeout(300);
ok('Jauge de mot de passe (largeur dynamique)', /width:\s*\d+%/.test(await p.locator('[x-bind\\:style="barStyle"]').first().getAttribute('style') || ''));
await p.goto('http://127.0.0.1:8002/dashboard/livres'); await p.getByText('Nouveau livre').click(); await p.waitForTimeout(800);
ok('Modale Livewire ouverte', await p.getByRole('dialog').isVisible());
await p.goto('http://127.0.0.1:8002/'); await p.keyboard.press('Control+k'); await p.keyboard.type('rapport'); await p.waitForTimeout(900);
ok('Recherche Ctrl K avec résultats', (await p.locator('[role=dialog] li a').count()) > 0);
await b.close();
